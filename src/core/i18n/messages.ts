const TABLES: Record<MessageLang, Table> = { tr: TR, en: EN, de: DE, ar: AR, ru: RU, el: EL };

export const MESSAGE_KEYS = Object.keys(TR) as MessageKey[];

export function messageLang(lang: unknown): MessageLang {
  if (typeof lang !== 'string') return 'tr';
  const code = lang
    .slice(0, 2)
    .split('')
    .map((c) => (c >= 'A' && c <= 'Z' ? String.fromCharCode(c.charCodeAt(0) + 32) : c))
    .join('');
  return (LANGS as readonly string[]).includes(code) ? (code as MessageLang) : 'tr';
}

export function tryMessage(lang: string, key: MessageKey): string | undefined {
  return (TABLES[messageLang(lang)] as Record<string, string>)[key];
}

export function t(lang: string, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const text = TABLES[messageLang(lang)][key];
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export const isRtl = (lang: string): boolean => messageLang(lang) === 'ar';
