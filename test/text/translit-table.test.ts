import { transliterate } from '../../src/core/text/translit';

describe('transliterate letter by letter', () => {
  it.each([
    ['а', 'a'],
    ['б', 'b'],
    ['в', 'v'],
    ['г', 'g'],
    ['д', 'd'],
    ['ж', 'j'],
    ['з', 'z'],
    ['и', 'i'],
    ['й', 'y'],
    ['к', 'k'],
    ['л', 'l'],
    ['м', 'm'],
    ['н', 'n'],
    ['о', 'o'],
    ['п', 'p'],
    ['р', 'r'],
    ['с', 's'],
    ['т', 't'],
    ['у', 'u'],
    ['ф', 'f'],
    ['х', 'h'],
    ['ц', 'c'],
    ['ч', 'c'],
    ['ш', 's'],
    ['щ', 's'],
    ['ъ', ''],
    ['ы', 'i'],
    ['ь', ''],
    ['э', 'e'],
    ['і', 'i'],
    ['ї', 'i'],
    ['є', 'e'],
    ['ґ', 'g'],
    ['ў', 'u'],
    ['ә', 'a'],
    ['ө', 'o'],
    ['ү', 'u'],
    ['қ', 'k'],
    ['ғ', 'g'],
    ['ң', 'n'],
    ['һ', 'h'],
  ])('Cyrillic %s -> "%s"', (letter, latin) => {
    expect(transliterate(letter)).toBe(latin);
  });

  it.each([
    ['α', 'a'],
    ['β', 'v'],
    ['γ', 'g'],
    ['δ', 'd'],
    ['ε', 'e'],
    ['ζ', 'z'],
    ['η', 'i'],
    ['θ', 't'],
    ['ι', 'i'],
    ['κ', 'k'],
    ['λ', 'l'],
    ['μ', 'm'],
    ['ν', 'n'],
    ['ξ', 'ks'],
    ['ο', 'o'],
    ['π', 'p'],
    ['ρ', 'r'],
    ['σ', 's'],
    ['τ', 't'],
    ['υ', 'i'],
    ['φ', 'f'],
    ['χ', 'h'],
    ['ψ', 'ps'],
    ['ω', 'o'],
    ['ϊ', 'y'],
  ])('Greek %s -> "%s"', (letter, latin) => {
    expect(transliterate(letter)).toBe(latin);
  });

  it.each([
    ['ου', 'u'],
    ['ει', 'i'],
    ['οι', 'i'],
    ['αι', 'e'],
    ['υι', 'i'],
    ['αυ', 'av'],
    ['ευ', 'ev'],
    ['ντ', 'd'],
    ['μπ', 'b'],
    ['γκ', 'g'],
    ['γγ', 'ng'],
    ['τσ', 'c'],
    ['τζ', 'c'],
  ])('Greek pair %s -> "%s"', (pair, latin) => {
    expect(transliterate(pair)).toBe(latin);
  });

  it.each([
    ['е', 'ye'],
    ['ю', 'yu'],
    ['я', 'ya'],
    ['ё', 'o'],
    ['бе', 'be'],
    ['бю', 'bu'],
    ['бя', 'ba'],
    ['бё', 'bo'],
    ['ае', 'aye'],
  ])('soft vowel %s -> "%s"', (text, latin) => {
    expect(transliterate(text)).toBe(latin);
  });
});
